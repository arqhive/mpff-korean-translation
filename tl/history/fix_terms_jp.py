# 태그가 섞여 통째로 치환이 안 되는 것들은 (en, jp) 짝으로 직접 지정한다
EXACT = {
    ("Cratered", "デスSミサイル"): "데스 S미사일",
    ("Pulverized", "チャージHショット"): "차지 H샷",
    ("{vs:-5}ROHKOR{p}POD{/vs}", "{vs:-5}ゴライアス{p}ポッド{/vs}"): "{vs:-5}고라이아스{p}포드{/vs}",
    ("ROHKOR BEETLE", "ゴライアス"): "고라이아스",
    ("{vs:-5}FLYING{p}PIRATE{/vs}", "{vs:-5}フライング{p}パイレーツ{/vs}"): "{vs:-5}비행{p}해적{/vs}",
}


def main():
    path = os.path.join(BASE, "ko.json")
    rows = json.load(open(path, encoding="utf-8"))
    n = 0
    for r in rows:
        if not r["ko"]:
            continue
        key = (r["en"], r["jp"])
        if key in EXACT:
            if r["ko"] != EXACT[key]:
                r["ko"] = EXACT[key]
                n += 1
            continue
        name = strip(r["jp"])
        if name in TABLE:
            new = r["jp"].replace(name, TABLE[name])
            # 치환 후에도 가나가 남으면 태그가 이름 사이에 끼어 있다는 뜻이라 건너뛴다
            if re.search(r"[ぁ-んァ-ヴ一-鿿]", strip(new)):
                print("  건너뜀(태그 끼임):", r["jp"])
                continue
            if r["ko"] != new:
                r["ko"] = new
                n += 1
    json.dump(rows, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    done = sum(1 for r in rows if r["ko"])
    print(f"{n}행 용어 수정 | 누적 {done}/{len(rows)} ({done * 100 // len(rows)}%)")


if __name__ == "__main__":
    main()
